def _append_gate_code(base_lines: list, var_prefix: str, feat: str, op: str, thresh: float):
    base_lines.append(f'        {var_prefix}_s = data["{feat}"].astype(float)')
    if op in ("<", ">"):
        base_lines.append(f"        {var_prefix}_gate = {var_prefix}_s {op} {thresh}")
        base_lines.append(f"        long_cond = long_cond & {var_prefix}_gate")
        base_lines.append(f"        short_cond = short_cond & {var_prefix}_gate")
    elif op == "align":
        abs_t = abs(float(thresh))
        base_lines.append(f"        long_cond = long_cond & ({var_prefix}_s >= -{abs_t})")
        base_lines.append(f"        short_cond = short_cond & ({var_prefix}_s <= {abs_t})")
    elif op == "strict_align":
        abs_t = abs(float(thresh))
        base_lines.append(f"        long_cond = long_cond & ({var_prefix}_s > {abs_t})")
        base_lines.append(f"        short_cond = short_cond & ({var_prefix}_s < -{abs_t})")


def parse_args():
    parser = argparse.ArgumentParser(description="Synthesize Sub-Era Invariant Quantitative Alpha Strategy")
    parser.add_argument("--name", type=str, required=True, help="Strategy class name (e.g. MicroAbsorptionAlpha)")
    parser.add_argument("--from-scan-rank", type=int, default=None, help="1-based rank from data/latest_edge_scan.json")
    parser.add_argument("--scan-json", type=str, default="data/latest_edge_scan.json", help="Path to edge scan JSON report")

    parser.add_argument("--symbol", type=str, default="OANDA:XAUUSD", help="Asset ticker")
    parser.add_argument("--tf", type=str, default="15m", help="Timeframe")
    parser.add_argument("--primary-feature", type=str, default=None, help="Primary stationary primitive from feature_factory")
    parser.add_argument("--polarity", type=str, choices=["continuation", "reversion"], default="continuation")
    parser.add_argument("--q-low", type=float, default=-0.5, help="Lower threshold for primary feature")
    parser.add_argument("--q-high", type=float, default=0.5, help="Upper threshold for primary feature")

    parser.add_argument("--regime-feature", type=str, default=None, help="Conditioning regime feature from feature_factory")
    parser.add_argument("--regime-op", type=str, choices=["<", ">", "align", "strict_align"], default=None, help="Operator for regime gate")
    parser.add_argument("--regime-thresh", type=float, default=None, help="Threshold for regime gate")

    parser.add_argument("--extra-filter-feature", type=str, default=None, help="Autopsy remediation filter feature")
    parser.add_argument("--extra-filter-op", type=str, choices=["<", ">", "align", "strict_align"], default=None, help="Autopsy remediation filter operator")
    parser.add_argument("--extra-filter-thresh", type=float, default=None, help="Autopsy remediation filter threshold")

    parser.add_argument("--sl-mult", type=float, default=None, help="Stop loss ATR multiplier (overrides scan geometry if set)")
    parser.add_argument("--tp-mult", type=float, default=None, help="Take profit ATR multiplier (overrides scan geometry if set)")
    parser.add_argument("--risk-pct", type=float, default=None, help="Risk percentage per trade (overrides scan geometry if set)")

    # Legacy compatibility flags
    parser.add_argument("--feature", type=str, default=None, help="Legacy feature flag")
    parser.add_argument("--archetype", type=str, default=None, help="Legacy archetype flag")
    parser.add_argument("--lookback", type=int, default=20, help="Legacy lookback flag")
    return parser.parse_args()


def main():
    args = parse_args()

    if args.from_scan_rank is not None:
        scan_path = os.path.join(PROJECT_ROOT, args.scan_json) if not os.path.isabs(args.scan_json) else args.scan_json
        if not os.path.exists(scan_path):
            print(f"[-] Scan JSON not found at {scan_path}. Run `python tools/scan_edge.py` first.", file=sys.stderr)
            sys.exit(1)
        with open(scan_path, "r") as f:
            scan_data = json.load(f)
        anomalies = scan_data.get("verified_conditional_anomalies", [])
        idx = args.from_scan_rank - 1
        if idx < 0 or idx >= len(anomalies):
            print(f"[-] Requested rank {args.from_scan_rank} out of range ({len(anomalies)} anomalies available).", file=sys.stderr)
            sys.exit(1)
        chosen = anomalies[idx]
        args.symbol = scan_data.get("symbol", args.symbol)
        args.tf = scan_data.get("timeframe", args.tf)
        args.primary_feature = chosen["primary_feature"]
        args.polarity = chosen["polarity"]
        args.q_low = chosen["q_low"]
        args.q_high = chosen["q_high"]
        args.regime_feature = chosen.get("regime_feature")
        args.regime_op = chosen.get("regime_op")
        args.regime_thresh = chosen.get("regime_thresh")
        geom = chosen.get("geometry", {})
        if args.sl_mult is None:
            args.sl_mult = geom.get("optimal_sl_atr_mult", 1.5)
        if args.tp_mult is None:
            args.tp_mult = geom.get("optimal_tp_atr_mult", 2.5)
        if args.risk_pct is None:
            args.risk_pct = geom.get("recommended_risk_pct_1r", 0.0030)

    if args.sl_mult is None:
        args.sl_mult = 1.5
    if args.tp_mult is None:
        args.tp_mult = 2.5
    if args.risk_pct is None:
        args.risk_pct = 0.0030

    if not args.primary_feature:
        if args.archetype == "mean_reversion":
            args.primary_feature = "coord_iqr_w21"
            args.polarity = "reversion"
            args.q_low = -1.35
            args.q_high = 1.35
        elif args.archetype == "range_breakout":
            args.primary_feature = "coord_ext_w13"
            args.polarity = "continuation"
            args.q_low = -0.15
            args.q_high = 0.15
        else:
            args.primary_feature = "path_eff_w13"
            args.polarity = "continuation"
            args.q_low = -0.35
            args.q_high = 0.35

    req_features = [args.primary_feature]
    if args.regime_feature and args.regime_feature not in req_features:
        req_features.append(args.regime_feature)
    if args.extra_filter_feature and args.extra_filter_feature not in req_features:
        req_features.append(args.extra_filter_feature)

    if args.polarity == "continuation":
        base_lines = [
            f"        long_cond = (p > {args.q_high}) & (p.shift(1) <= {args.q_high})",
            f"        short_cond = (p < {args.q_low}) & (p.shift(1) >= {args.q_low})",
        ]
    else:
        base_lines = [
            f"        long_cond = (p < {args.q_low}) & (p.shift(1) >= {args.q_low})",
            f"        short_cond = (p > {args.q_high}) & (p.shift(1) <= {args.q_high})",
        ]

    rule_desc = f"{args.primary_feature} ({args.polarity}: [{args.q_low}, {args.q_high}])"

    if args.regime_feature and args.regime_op and args.regime_thresh is not None:
        _append_gate_code(base_lines, "reg", args.regime_feature, args.regime_op, args.regime_thresh)
        rule_desc += f" AND {args.regime_feature} {args.regime_op} {args.regime_thresh}"

    if args.extra_filter_feature and args.extra_filter_op and args.extra_filter_thresh is not None:
        _append_gate_code(base_lines, "extra", args.extra_filter_feature, args.extra_filter_op, args.extra_filter_thresh)
        rule_desc += f" AND {args.extra_filter_feature} {args.extra_filter_op} {args.extra_filter_thresh}"

    content = ML_STRATEGY_TEMPLATE.format(
        name=args.name,
        symbol=args.symbol,
        tf=args.tf,
        rule_summary=rule_desc,
        project_root=PROJECT_ROOT,
        risk_pct=args.risk_pct,
        sl_mult=args.sl_mult,
        tp_mult=args.tp_mult,
        required_features_list=repr(req_features),
        primary_feature=args.primary_feature,
        signal_logic="\n".join(base_lines),
    )

    alpha_dir = os.path.join(WORKSPACE_ROOT, "zillionsAlpha", "strategies")
    os.makedirs(alpha_dir, exist_ok=True)
    strategy_path = os.path.join(alpha_dir, f"{args.name}.py")

    with open(strategy_path, "w") as f:
        f.write(content)
    print(f"[+] Created ML-discovered strategy source: {strategy_path}")
    print(f"    Rule   : {rule_desc}")
    print(f"    Geometry: SL={args.sl_mult}x ATR | TP={args.tp_mult}x ATR | 1R Risk={args.risk_pct*100:.2f}%")

    skills_strat_dir = os.path.join(PROJECT_ROOT, "strategies")
    os.makedirs(skills_strat_dir, exist_ok=True)
    symlink_path = os.path.join(skills_strat_dir, f"{args.name}.py")
    if os.path.exists(symlink_path) or os.path.islink(symlink_path):
        os.remove(symlink_path)

    rel_source = os.path.relpath(strategy_path, skills_strat_dir)
    os.symlink(rel_source, symlink_path)
    print(f"[+] Symlinked to engine: {symlink_path}")
    print(f"[+] Ready to audit: python tools/run_backtest_audit.py --strategy {args.name}.py --days 30")


if __name__ == "__main__":
    main()
